#!/usr/bin/env python3
"""Rebuild the pooled overround regression and its LaTeX table.

Run from this folder with ``python3 regression_clustered.py``.
Requires pandas, statsmodels, and openpyxl.
"""

from pathlib import Path
import re

import pandas as pd
import statsmodels.formula.api as smf


ROOT = Path(__file__).resolve().parent
WORKBOOK = ROOT / "PairedOdds_with_Game_ID.xlsx"
OUTPUT = ROOT / "latex_tables" / "regression_overround.tex"

BOOKS = ["FanDuel", "BetMGM", "BetRivers", "Caesars", "DraftKings", "William Hill (US)"]
MARKETS = [
    "player_pass_completions",
    "player_pass_attempts",
    "player_pass_interceptions",
    "player_pass_longest_completion",
    "player_pass_tds",
    "player_pass_yds",
]
MARKET_LABELS = {
    "player_pass_completions": "Pass completions",
    "player_pass_attempts": "Pass attempts",
    "player_pass_interceptions": "Pass interceptions",
    "player_pass_longest_completion": "Longest completion",
    "player_pass_tds": "Pass TDs",
    "player_pass_yds": "Pass yards",
}


def coefficient_keys(names):
    """Map each fitted parameter to its bookmaker and market."""
    keys = {}
    for name in names:
        if name == "Intercept":
            keys[(None, None)] = name
            continue
        levels = re.findall(r"\[T\.([^\]]+)\]", name)
        if ":" in name:
            keys[(levels[0], levels[1])] = name
        elif "Bookmaker" in name:
            keys[(levels[0], None)] = name
        else:
            keys[(None, levels[0])] = name
    return keys


def p_value(value):
    return "$<0.001$" if value < 0.001 else f"{value:.3f}"


def main():
    data = pd.read_excel(
        WORKBOOK,
        sheet_name="PairedOdds",
        usecols=["Bookmaker", "Market", "Overround", "Game_ID"],
        engine="openpyxl",
    )
    data["Overround"] = pd.to_numeric(data["Overround"], errors="coerce")
    sample = data.dropna(subset=["Bookmaker", "Market", "Overround", "Game_ID"]).copy()

    if set(sample["Bookmaker"]) != set(BOOKS) or set(sample["Market"]) != set(MARKETS):
        raise ValueError("Bookmaker or market categories changed; review the reference categories.")

    # Rescaling the outcome changes coefficient units, not the model's t statistics.
    sample["overround_pp"] = 100 * sample["Overround"]
    sample["Bookmaker"] = pd.Categorical(sample["Bookmaker"], categories=BOOKS)
    sample["Market"] = pd.Categorical(sample["Market"], categories=MARKETS)
    game_ids = pd.factorize(sample["Game_ID"], sort=True)[0]

    formula = (
        'overround_pp ~ C(Bookmaker, Treatment(reference="FanDuel"))'
        ' * C(Market, Treatment(reference="player_pass_completions"))'
    )
    model = smf.ols(formula, data=sample)
    result = model.fit(
        cov_type="cluster",
        cov_kwds={"groups": game_ids, "use_correction": True, "df_correction": True},
        use_t=True,
    )
    keys = coefficient_keys(result.params.index)
    intervals = result.conf_int()
    cell_n = sample.groupby(["Bookmaker", "Market"], observed=True).size()

    lines = [
        "% Generated by regression_clustered.py",
        r"\begin{table}[H]",
        r"\centering",
        r"\caption{Pooled OLS estimates of quoted overround}",
        r"\label{tab:overround_regression}",
        r"\footnotesize",
        r"\setlength{\tabcolsep}{2.5pt}",
        r"\renewcommand{\arraystretch}{0.95}",
        r"\begin{tabular}{lrrrlr}",
        r"\toprule",
        r"Term & Estimate (pp) & Clustered SE (pp) & $p$-value & 95\% CI (pp) & $N$ \\",
        r"\midrule",
    ]

    def add_row(label, key):
        name = keys[key]
        estimate = result.params[name]
        se = result.bse[name]
        low, high = intervals.loc[name]
        book = key[0] or "FanDuel"
        market = key[1] or "player_pass_completions"
        n = int(cell_n.loc[(book, market)])
        lines.append(
            f"{label} & {estimate:.3f} & {se:.3f} & {p_value(result.pvalues[name])} "
            f"& [{low:.3f}, {high:.3f}] & {n:,} " + r"\\"
        )

    add_row("FanDuel, pass completions", (None, None))
    lines += [r"\addlinespace", r"\multicolumn{6}{l}{\emph{Markets at FanDuel, relative to completions}} \\"]
    for market in MARKETS[1:]:
        add_row(MARKET_LABELS[market], (None, market))

    lines += [r"\addlinespace", r"\multicolumn{6}{l}{\emph{Sportsbooks relative to FanDuel, for completions}} \\"]
    for book in BOOKS[1:]:
        add_row(book, (book, None))

    lines += [r"\addlinespace", r"\multicolumn{6}{l}{\emph{Additional bookmaker--market differences}} \\"]
    for book in BOOKS[1:]:
        for market in MARKETS[1:]:
            add_row(f"{book} $\\times$ {MARKET_LABELS[market]}", (book, market))

    lines += [
        r"\bottomrule",
        r"\end{tabular}",
        r"\par\vspace{4pt}",
        r"\begin{minipage}{0.95\textwidth}",
        r"\footnotesize",
        (
            rf"\emph{{Notes:}} {len(sample):,} observations across "
            rf"{sample['Game_ID'].nunique()} games; $R^2={result.rsquared:.3f}$. "
            r"The outcome, estimates, and SEs are in percentage points. "
            r"SEs are clustered by game; $p$-values and intervals use a "
            rf"$t$ distribution with {result.df_resid_inference:.0f} degrees of freedom. "
            r"$N$ counts observations in the indicated bookmaker--market cell, "
            r"including repeated collection snapshots; each coefficient is estimated using the full sample. "
            r"FanDuel passing completions is the reference group."
        ),
        r"\end{minipage}",
        r"\end{table}",
    ]
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {OUTPUT} ({len(sample):,} observations, {sample['Game_ID'].nunique()} games)")
    print(f"R-squared: {result.rsquared:.3f}; covariance: {result.cov_type}")
    caesars = result.params[keys[("Caesars", None)]]
    caesars_yards = result.params[keys[("Caesars", "player_pass_yds")]]
    print(f"Caesars vs FanDuel, completions: {caesars:.3f} pp")
    print(f"Caesars vs FanDuel, yards: {caesars + caesars_yards:.3f} pp")


if __name__ == "__main__":
    main()
